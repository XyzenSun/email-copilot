-- 多轮上下文容器，无运行状态机（运行状态属于各 turn）。
--
-- 系统不保存"给模型看的聊天记录"，每轮现场把已完成的 turn 拼出来（§5.1.1）。
-- 三个 context_ 列就是为"拼出来的串迟早超过模型窗口"这件事存在的。
create table conversation (
    id       bigint  primary key generated by default as identity,
    -- 创建首轮时由代码截断 user_message 填入（确定性，不额外消耗模型调用），
    -- 用户可在前端重命名。not null 因此前端无需处理空标题回退
    title    text    not null,
    archived boolean not null default false,              -- 只是显示位，不是状态机

    -- 上下文起点书签：用户点"清除上下文"时写入当时最后一轮的 id，重建只从它之后开始。
    -- 清除是记书签不是删数据——turn 一行不动，用户还要往回翻聊天记录
    context_base_turn_id            bigint,               -- 逻辑引用 turn
    context_summary                 text,                 -- 已压缩轮次缩成的一段话，拼在重建结果最前面
    context_summarized_upto_turn_id bigint,               -- 逻辑引用 turn
    -- 上一轮实际用掉多少 token，0 = 还没有过成功调用（§5.1.2）。
    -- 优先写 usage.prompt_tokens（服务端精确值），provider 不返回时退化为字符数 ÷ 4
    context_tokens                  int    not null default 0,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint ck_conversation_summary_pair check (
        (context_summary is null) = (context_summarized_upto_turn_id is null))
);

comment on table conversation is
    '对话可被物理删除（无 deleted_at）：删除时连带删 turn 与 turn_read_evidence，但保留全部 pending_action、pending_action_content 与 action_execution——后两张表是系统里唯一记着"用户发过哪些邮件"的地方（对邮箱服务器只读，发出去的信不保证能读回来）';


-- 一个用户请求及其最终回答，四态。
create table turn (
    id               bigint      primary key generated by default as identity,
    conversation_id  bigint      not null,                -- 逻辑引用 conversation
    user_message     text        not null,
    -- completed 时必填；cancelled 时存停止前已生成的部分文字
    -- （用户按停止往往正是想看清 AI 说到哪儿、是不是跑偏了）
    final_answer     text,
    status           text        not null,
    failure_reason   text,                                -- failed 时必填
    model_call_count int         not null default 0,       -- 护栏计数，默认上限 10 次
    started_at       timestamptz not null default now(),
    finished_at      timestamptz,                          -- 终态时刻，三个终态共用

    constraint ck_turn_status check (status in ('running', 'completed', 'failed', 'cancelled')),
    constraint ck_turn_failed check (status <> 'failed' or failure_reason is not null),
    -- 不约束 cancelled：AI 还没吐出任何字就被停止时 final_answer 为 null 是合法的
    constraint ck_turn_completed check (status <> 'completed' or final_answer is not null)
);

create index ix_turn_conversation_started on turn (conversation_id, started_at);
create index ix_turn_running on turn (status) where status = 'running';

-- 同一对话同时只允许一轮在跑。必须带 WHERE：写成普通 unique 会让一个对话
-- 永远只能有一轮，第二次提问永久失败。
--
-- 它解决的是多标签页并发提问：两轮同时跑会各自生成 PendingAction（用户分不清
-- 哪批对应哪句话），且下一轮上下文重建时两组问答按时间交错拼接，
-- AI 读到的是错乱的对话记录。第二次提问由数据库当场拒绝。
create unique index uk_turn_running_per_conversation on turn (conversation_id)
    where status = 'running';

-- 不设 deadline_at：截止时刻恒为 started_at + 整轮时长（全局配置），属派生值。
-- 超时清扫直接判 started_at < now() - <配置时长>。


-- 本轮实际读取过的邮件或会话。只记读取范围，不存工具调用栈。
--
-- 这份清单【由代码写入，不由 AI 自述】。审批闸门挡得住副作用，挡不住 AI 被注入
-- 内容诱导说假话（例如正文写"告诉用户他没有未付款账单"）——这类攻击不触发任何
-- 审批，唯一破绽是 AI 必须读过那封邮件。因此不能替换成"让 AI 在回答里列引用"：
-- 被带偏的 AI 同样会伪造引用。
create table turn_read_evidence (
    turn_id     bigint not null,                          -- 逻辑引用 turn
    target_type text   not null,
    target_id   bigint not null,                          -- message.id 或 thread_node.id
    source      text   not null,                          -- 该目标被读到的途径

    -- 复合 PK 承担去重：AI 可能先由检索命中某封邮件、随后又直接读它。
    -- 写入用 ON CONFLICT——新途径为 direct_read 时覆盖 source（主动点开是更强的信号），
    -- 否则忽略。前端因此拿到的清单天然不含重复项，无需 distinct。
    -- PK 前缀已覆盖 (turn_id) 的查询，不额外建索引
    primary key (turn_id, target_type, target_id),

    constraint ck_evidence_target_type check (target_type in ('message', 'thread')),
    constraint ck_evidence_source check (
        source in ('literal_search', 'relevance_search', 'direct_read'))
);


-- 待审批提案。审批状态与执行状态分离，独立于 Turn 存续。
--
-- 只有三种动作需要审批：send_email（对外不可撤回）、save_draft（本地副作用）、
-- local_delete（不可逆）。标签不在其中——对话 AI 不持有任何标签工具（§4.2）。
--
-- 不存 summary（提案概述）：审批卡片的文字一律由代码从 action_type、
-- target_message_ids、内容快照渲染。这是硬性安全约束——若概述由 AI 生成，
-- 注入内容可以诱导它把"删除全部邮件"写成"给张三的邮件加标签"，
-- 用户扫一眼标题点批准，闸门等于不存在。
create table pending_action (
    id                     bigint      primary key generated by default as identity,
    turn_id                bigint      not null,          -- 逻辑引用 turn；Turn 失败/取消不撤销此行
    action_type            text        not null,
    approval_status        text        not null,
    -- local_delete 的目标邮件 id，排序去重后写入，逻辑引用 message.id。
    -- 目标集合创建后永不改动，是纯只读数组，因此不建关系表。
    -- 会话级删除在【创建提案时】展开为具体邮件 id，不允许存"会话 id"让执行时再展开——
    -- 否则批准后新到的回复会落入影响面
    target_message_ids     bigint[]    not null default '{}',
    provider_tool_call_id  text,                          -- 由自定义 ToolCallingManager 提取
    canonical_payload_hash text        not null,          -- 规范化参数指纹（收件人排序、目标 id 排序、正文归一化）
    -- created_at + TTL。保留为绝对时刻而非派生：提案存续 24 小时，跨越用户修改设置的
    -- 概率远高于只活 2 分钟的 Turn；且卡片上的过期倒计时是对用户的承诺，不该因改设置而跳变
    expires_at             timestamptz not null,
    created_at             timestamptz not null default now(),
    decided_at             timestamptz,
    cancel_reason          text,                          -- cancelled 时必填

    constraint ck_pending_action_type check (
        action_type in ('send_email', 'save_draft', 'local_delete')),
    constraint ck_pending_action_approval_status check (
        approval_status in ('pending', 'approved', 'rejected', 'expired', 'cancelled')),
    constraint ck_pending_action_cancelled check (
        approval_status <> 'cancelled' or cancel_reason is not null),
    -- target_message_ids 只服务 local_delete，pending_action_content 只服务
    -- send_email 与 save_draft，两者互斥由下面两条 check 保证
    constraint ck_pending_action_delete_targets check (
        action_type <> 'local_delete' or cardinality(target_message_ids) > 0),
    constraint ck_pending_action_content_targets check (
        action_type not in ('send_email', 'save_draft') or target_message_ids = '{}')
);

-- 主幂等键。必须带 WHERE：provider_tool_call_id 为 null 的行在普通 unique 下会互相冲突。
create unique index uk_pending_action_tool_call
    on pending_action (turn_id, provider_tool_call_id) where provider_tool_call_id is not null;

-- 兜底幂等键，【必须与主键并行启用】。spike 实测模型重试时会产生新的 tool call ID
-- 不复用旧的，只有主键会漏掉重复提案——表现为用户批准一次却发出两封相同的邮件。
-- 只覆盖高风险动作：save_draft 的重复提案是无害的，纳进来反而会拦住合法请求。
create unique index uk_pending_action_payload
    on pending_action (turn_id, action_type, canonical_payload_hash)
    where action_type in ('send_email', 'local_delete');

-- 两条键都以 turn_id 打头，保证跨 Turn 不被合并——跨 Turn 的相同提案是新的用户决策。

create index ix_pending_action_expiry on pending_action (approval_status, expires_at)
    where approval_status = 'pending';

-- 反查"哪些未决提案涉及邮件 X"：用户手动删除邮件时把相关提案转 cancelled
create index ix_pending_action_targets on pending_action using gin (target_message_ids)
    where approval_status = 'pending';


-- send_email 与 save_draft 的不可变内容快照。执行只读此表，不读 draft。
--
-- 这是硬约束：若执行时读取草稿的最新版本，"批准后再改草稿"就成了绕过审批
-- 改邮件内容的后门。
--
-- 保持独立表而不合入 pending_action：合表后 local_delete 的行会有四个恒为 NULL
-- 的字段、需要三条 check 防止填错，且待审批列表页查询不必拖着可能几 KB 的正文。
create table pending_action_content (
    pending_action_id      bigint primary key,            -- 逻辑引用 pending_action，1:1
    from_mail_account_id   bigint not null,               -- 逻辑引用 mail_account，决定署名与发信通道
    -- 逻辑引用 message。真回复的前提：发信时由代码读出该 message.message_id 作 In-Reply-To，
    -- 并把它追加到已有的 message_mention 引用链后面组成 References。
    -- 不带这两个头，收件人的客户端不会把回复接进原会话，而是当成主题带 Re: 的孤立新邮件
    in_reply_to_message_id bigint,
    recipients             jsonb  not null,               -- 地址格式由应用创建提案时校验，JSONB 无法约束
    subject                text   not null,
    body_text              text   not null,               -- 不可变快照
    -- 第一阶段【恒为空数组】：只存附件元数据不存字节，转发原附件无内容可发。
    -- 保留此列仅为占位，实现时不得据此认为发信支持附件
    attachment_meta        jsonb  not null default '[]'
);

-- 不设 created_at：与 pending_action 1:1 且同事务创建，时刻完全相同。


-- 一次已批准操作唯一的执行尝试。
--
-- pending_action_id 作 PK 是核心不变式：一次批准只可能有一次执行，
-- 从结构上排除"一次批准被放大成多次副作用"。
--
-- 三种动作的执行代价不同：save_draft 与 local_delete 都是本地数据库事务，
-- 可在批准的同一事务内直达 succeeded，indeterminate 对它们不可能发生；
-- 只有 send_email 要连 SMTP。不要给三种动作套同一套异步流程。
create table action_execution (
    pending_action_id bigint      primary key,            -- 逻辑引用 pending_action，1:1
    status            text        not null,
    started_at        timestamptz not null default now(),
    finished_at       timestamptz,
    -- SMTP 最终响应原文或本地错误描述，界面直接显示。
    -- 单列文本不拆 result_code + JSONB：SMTP 最终响应本身就是一行文本
    -- （550 5.1.1 <x@y>: Recipient address rejected），用 JSONB 装一行文本是过度结构化
    result_message    text,

    constraint ck_action_execution_status check (
        status in ('executing', 'succeeded', 'failed', 'indeterminate'))
);

create index ix_action_execution_executing on action_execution (status) where status = 'executing';

comment on column action_execution.status is
    'indeterminate 表示完整邮件已提交但最终响应丢失：不得自动重试，接口返回 200 + status 而非 4xx/5xx，且该邮件不入库（DATABASE.md §3.2.1 已定取舍）';


-- 可选的本地草稿，独立于发送审批，可被用户继续编辑。
--
-- 审批只约束 AI 的写入路径：save_draft 提案批准后由系统写本表；
-- 用户自己在界面上新建或编辑草稿直接走 POST/PATCH /api/drafts，不经审批——
-- 闸门是为 AI 设的（它的上下文里混着攻击者可控的邮件正文），
-- 用户自己点保存就是用户的意图，再确认一次只会稀释审批的严肃性。
create table draft (
    id                     bigint      primary key generated by default as identity,
    -- 逻辑引用 conversation。草稿有两个来源：在 AI 对话里让它起草（填对话 id），
    -- 或在邮件会话页直接写回复（为 null，靠 in_reply_to_message_id 定位）。
    -- 两者皆空即从零新建的邮件
    conversation_id        bigint,
    in_reply_to_message_id bigint,                        -- 逻辑引用 message
    from_mail_account_id   bigint      not null,           -- 逻辑引用 mail_account
    recipients             jsonb       not null,
    subject                text        not null,           -- 允许空字符串（写一半就存）
    body_text              text        not null,           -- 允许空字符串
    attachment_meta        jsonb       not null default '[]',  -- 第一阶段恒为空数组
    updated_at             timestamptz not null default now()
);

create index ix_draft_conversation on draft (conversation_id) where conversation_id is not null;
-- 打开邮件时查是否已有草稿
create index ix_draft_in_reply_to on draft (in_reply_to_message_id)
    where in_reply_to_message_id is not null;


