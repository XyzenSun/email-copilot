-- ═══════════════════════════════════════════════════════════════════════════
-- email-copilot 初始 schema：21 张表
--
-- 权威定义：DATABASE.md §3–§8（逐列）与 §10（表清单）。
--
-- 三条贯穿全库的原则（DATABASE.md §1），读本文件时先记住：
--
--  1. 不建任何外键约束。所有跨表引用由 Java 代码维护，`*_id` 列只是逻辑引用。
--     理由：单用户单库，FK 带来的级联/锁/迁移成本高于收益。
--     唯一约束、check、索引仍建在数据库层——它们承担去重、幂等和查询，必须 DB 保证。
--
--  2. 控制流一律 typed columns。阶段、状态、重试次数、错误码、租约都参与
--     过滤、比较或原子更新，禁止进 JSON。JSONB 只装只读弹性数据（收件人列表、
--     附件元数据、IMAP 文件夹列表）。
--
--  3. 派生值不落库。唯一例外是 pending_action.expires_at——24 小时的过期承诺
--     不该因为用户改了配置就跳变。
--
-- 蕴含式约束 `A ⇒ B` 一律写成 `not A or B`。注意 check 在结果为 NULL 时视为通过
-- （不同于 WHERE），因此左侧必须是 not null 列，否则约束会被静默绕过。
-- 本文件里所有蕴含式约束的左侧列均已核对为 not null。
--
-- 时间列同时给 DB 默认值与应用层自动填充：应用层是主路径（避免漏写 updated_at
-- 造成"更新了但时间没变"的脏数据），DB 默认值是兜底（让 migration 内的 INSERT
-- 与测试里的裸 SQL 也能满足 not null）。
-- ═══════════════════════════════════════════════════════════════════════════


