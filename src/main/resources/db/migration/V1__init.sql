-- 邮箱账号接入配置。一个账号同时持有收信（IMAP）与发信（SMTP）配置。
-- 账号用户名明文保存（非凭据）；密码是凭据，归 external_account_secret。
--
-- 没有 enabled 总开关列：两个通道各自的 *_enabled 已表达全部状态，"停用账号"就是
-- 把两个都置 false。多一个总开关会产生"总开关关了但 imap_enabled 还是 true"这类
-- 无意义组合，且每处判断都要同时看两层。
create table mail_account (
    id              bigint      primary key generated by default as identity,
    email_address   text        not null,
    display_name    text        not null,                 -- 展示名，兼作发信署名
    imap_host       text,
    imap_port       int,
    imap_username   text,                                 -- 明文，非凭据
    imap_folders    jsonb,                                -- 同步文件夹列表，只读弹性
    imap_enabled    boolean     not null default false,
    smtp_host       text,
    smtp_port       int,
    smtp_username   text,                                 -- 明文，非凭据
    smtp_enabled    boolean     not null default false,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),

    constraint uk_mail_account_email_address unique (email_address),
    constraint ck_mail_account_imap_config check (
        imap_enabled = false
        or (imap_host is not null and imap_port is not null and imap_username is not null)),
    constraint ck_mail_account_smtp_config check (
        smtp_enabled = false
        or (smtp_host is not null and smtp_port is not null and smtp_username is not null))
);

comment on table mail_account is
    '邮箱账号。删除前置条件是两个通道全部停用，且删除时连带物理删除该账号的全部邮件（API.md §12.3）';


-- 按账号、按 mailbox 持久化 IMAP 增量状态。
-- UID/UIDVALIDITY 属于 mailbox 自己的命名空间，不能压在 mail_account 上共用一个账号级游标。
-- 全库不建外键；mail_account_id 由应用层在账号删除事务中维护。
create table imap_folder_cursor (
    id                 bigint primary key generated by default as identity,
    mail_account_id    bigint not null,                    -- 逻辑引用 mail_account
    folder_name        text not null,                      -- 服务器返回的完整 mailbox 名
    initial_sync_since timestamptz not null,               -- 首次建立时固定，不随设置变化
    uid_validity       bigint not null,
    last_seen_uid      bigint not null default 0,
    claimed_by         text,
    claim_until        timestamptz,
    version            int not null default 0,
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now(),

    constraint uk_imap_folder_cursor
        unique (mail_account_id, folder_name),
    constraint ck_imap_cursor_uid_validity
        check (uid_validity between 1 and 4294967295),
    constraint ck_imap_cursor_last_uid
        check (last_seen_uid between 0 and 4294967295),
    constraint ck_imap_cursor_version
        check (version >= 0)
);

comment on table imap_folder_cursor is
    'IMAP mailbox 级 UID 水位与租约；不保存 INBOX/Junk 角色，也不决定邮件分类';

comment on column imap_folder_cursor.initial_sync_since is
