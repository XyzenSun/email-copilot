comment on column imap_folder_cursor.last_seen_uid is
    '已达到终态的最大 UID，不是 UIDNEXT；只允许通过版本 CAS 向前推进';


-- 全局会话节点，跨账号共享。被提及但未收到的邮件也有节点，因此节点先于 message 存在。
--
-- 会话摘要不在此表缓存：会话内容随往来动态变化，缓存会过时，每次由 AI 现算。
create table thread_node (
    id             bigint      primary key generated by default as identity,
    rfc_message_id text        not null,                  -- 全局 Message-ID
    created_at     timestamptz not null default now(),

    constraint uk_thread_node_rfc_message_id unique (rfc_message_id)
);


-- 一封具体邮件。收到的与自己发出的都在本表，由 direction 区分。
--
-- 同表而非另建发信表的理由（§3.2.1）：会话视图必须把用户的回复插回时间线，
-- 否则整段往来只剩对方发言、看起来像自言自语；另建一张表则要在每个会话查询里
-- union 两张表。"发出的邮件也是一封邮件"本来就成立。
create table message (
    id                        bigint      primary key generated by default as identity,
    mail_account_id           bigint      not null,       -- 逻辑引用 mail_account；outbound 时为发信账号
    direction                 text        not null default 'inbound',
    -- 发信方给的 RFC Message-ID；缺失时填合成标识；
    -- outbound 时是发信时由代码自己生成并写入邮件头的值，因此永不为空、也不需要 fingerprint
    message_id                text        not null,
    fingerprint               text,                       -- 无标识邮件的启发式指纹；有 message_id 时为 null
    thread_node_id            bigint      not null,       -- 逻辑引用 thread_node
    from_display              text,                       -- 发件人显示名，不可信，仅列表展示
    from_address              text        not null,       -- 发件人邮箱地址（字面）
    from_address_domain       text        not null,       -- 从 from 解析的字面域名
    -- DKIM 通过且签名域与发件人域对齐时才填，否则 null。outbound 恒 null。
    -- 发件人规则匹配的是这一列，不是 from_address 字面值——否则伪造 From 就能绕过屏蔽
    from_authenticated_domain text,
    -- 收件人/抄送/密送。inbound 也填：解析 MIME 时本就拿到了 To/Cc，
    -- 顺带支持界面区分"这封直接发给我"与"我只是被 Cc"
    recipients                jsonb       not null default '{"to": [], "cc": [], "bcc": []}',
    subject                   text,
    base_subject              text,                       -- 剥离 Re:/Fwd: 后的核心主题
    received_at               timestamptz not null,       -- 时间判定唯一依据；outbound 时为 SMTP 受理时刻
    sent_at                   timestamptz,                -- 发件人填写，可伪造，仅展示
    body_text                 text,                       -- 规范正文；DataPurge 后置空
    translated_body           text,                       -- 仅非目标语言时填；DataPurge 后置空
    summary                   text,                       -- 单封摘要；DataPurge 后置空
    category                  text,
    tags                      bigint[]    not null default '{}',  -- 逻辑引用 tag.id，不建关系表
    spam_score                numeric,                    -- 垃圾置信度，元数据
    classified_at             timestamptz,                -- 垃圾判定与分类统一记此时刻
    dkim_passed               boolean,                    -- outbound 为 null（不校验自己发的信）
    deleted_at                timestamptz,                -- 软删除标记
    purged                    boolean     not null default false,
    created_at                timestamptz not null default now(),

    constraint ck_message_direction check (direction in ('inbound', 'outbound')),
    constraint ck_message_category check (
        category in ('primary', 'transaction', 'promotion', 'social', 'update', 'spam')),
    constraint ck_message_spam_score check (spam_score >= 0 and spam_score <= 1),
    constraint ck_message_inbound_dkim check (direction <> 'inbound' or dkim_passed is not null),
    -- 判定流水线不跑 outbound：那是用户自己写的内容，判定它毫无意义且白花模型调用
    constraint ck_message_outbound_no_judgment check (
        direction <> 'outbound'
        or (category is null and spam_score is null and fingerprint is null)),

    -- 去重唯一约束：IMAP 并发/重复到达时由数据库拒绝重复。
    -- 不含 deleted_at 条件——软删除的行仍占位，删除记忆必须比邮件本体活得更久，
    -- 否则删掉的邮件会被下一次同步重新收进来。
    -- 同一约束顺带解决"IMAP 从 Sent 读到自己发出的副本"（§3.2.1），现有约束原样复用。
    constraint uk_message_account_message_id unique (mail_account_id, message_id)
);

-- 无标识邮件的去重。必须带 WHERE：有 message_id 的行 fingerprint 全为 null，
-- 写成普通 unique 会让它们互相冲突，第二封有标识的邮件就永远入不了库。
create unique index uk_message_account_fingerprint
    on message (mail_account_id, fingerprint) where fingerprint is not null;

create index ix_message_thread_received on message (thread_node_id, received_at);
-- 收件箱列表（direction='inbound'）与已发送视图（'outbound'）共用
create index ix_message_direction_received on message (direction, received_at);
-- 首次接入窗口的时间范围扫描，不带 direction 条件
create index ix_message_received on message (received_at);
create index ix_message_authenticated_domain
    on message (from_authenticated_domain) where from_authenticated_domain is not null;
create index ix_message_address_domain on message (from_address_domain);
create index ix_message_category on message (category) where category is not null;
-- 标签数组包含查询 tags @> ARRAY[<id>]
create index ix_message_tags on message using gin (tags);
create index ix_message_active on message (deleted_at) where deleted_at is null;

comment on column message.tags is
    '标签 id 数组，逻辑引用 tag.id。不建关系表（DATABASE.md §4.2）：只读 id 集合用原生数组列 + GIN 索引已足够';


-- 同一封邮件被多通道送达时的来源元数据，FirstIngestWins 的载体。
-- 后续通道只记来源，不比较内容差异、不替换 message.body_text。
create table message_source (
    id            bigint      primary key generated by default as identity,
    message_id_pk bigint      not null,                   -- 逻辑引用 message
    channel_type  text        not null,                   -- 'smtp' 表示本系统发出
    is_canonical  boolean     not null,                   -- 首次入库的通道为 true，全表每封邮件仅一条
    received_at   timestamptz not null,

    constraint ck_message_source_channel check (channel_type in ('imap', 'smtp')),
    -- 一封邮件同一通道只记一条。正好允许 outbound 邮件同时有
    -- ('smtp', canonical) 与后来 IMAP 读到 Sent 副本的 ('imap', 非 canonical) 两条
    constraint uk_message_source unique (message_id_pk, channel_type)
);

-- 每封邮件最多一条 canonical source（数据库不变式）。
-- 若已有违规数据，建索引应明确失败，不能静默挑选。
create unique index uk_message_source_one_canonical
    on message_source (message_id_pk)
    where is_canonical = true;


-- message 列出的上游引用（References / In-Reply-To）。
-- 引用目标可能本系统未持有，但 thread_node 已为其建节点，
-- 因此 referenced_rfc_message_id 可 join thread_node.rfc_message_id 找到节点。
create table message_mention (
    message_id_pk             bigint not null,            -- 逻辑引用 message
    referenced_rfc_message_id text   not null,
    position                  int    not null,            -- 在 References 中的顺序

    primary key (message_id_pk, referenced_rfc_message_id)
);

-- 反向查找谁引用了某节点
create index ix_message_mention_referenced on message_mention (referenced_rfc_message_id);


-- 邮件附件，第一阶段只存元数据不解析内容、无下载接口
-- （附件是攻击载荷最集中的位置）。DataPurge 时直接删行，无最小记忆需求。
create table attachment (
    id            bigint primary key generated by default as identity,
    message_id_pk bigint not null,                        -- 逻辑引用 message
    filename      text   not null,
    content_type  text,
    size_bytes    int    not null
);

create index ix_attachment_message on attachment (message_id_pk);


-- 标签。name 是字符串标识，创建后不可改；id 是自增主键，用于 message.tags 数组引用。
--
-- description 不是给人看的备注，而是打标签那一步实际拼进提示词的内容（§4.2.1）——
-- 改描述即改标注行为，不需要改代码也不需要重启。这正是把它设计成 not null 文本列的原因。
create table tag (
    id           bigint      primary key generated by default as identity,
    name         text        not null,                    -- 限 [A-Za-z0-9]，由应用层校验，不设 DB check
    display_name text        not null,
    description  text        not null,                    -- 写给 AI 的判定依据，会被原样注入提示词
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),

    constraint uk_tag_name unique (name)
);


-- 每封邮件一份当前进度，单行阶段游标。stage 指的是【下一项待执行阶段】。
--
-- 只有 direction='inbound' 的邮件才建本表的行（§3.2.1），因此领取队列的查询
-- 天然只看得到收到的邮件，无须额外条件。
--
-- 判定结果不进本表（游标只指位置，不承载业务结果），分类/垃圾/翻译/摘要
-- 都是 message 的 typed columns。
create table processing_progress (
    message_id_pk     bigint      primary key,            -- 一封一行，逻辑引用 message
    stage             text        not null,
    status            text        not null,
    in_progress_since timestamptz,                        -- status=in_progress 时必填，用于识别僵尸
    retry_count       int         not null default 0,
    last_error_code   text,
    last_error_at     timestamptz,

    constraint ck_processing_stage check (stage in (
        'sender_rule', 'spam_judgment', 'classification',
        'language_detection', 'translation', 'summary', 'done')),
    constraint ck_processing_status check (status in ('pending', 'in_progress', 'completed', 'failed')),
    constraint ck_processing_in_progress check (status <> 'in_progress' or in_progress_since is not null),
    constraint ck_processing_failed check (status <> 'failed' or last_error_code is not null)
);

create index ix_processing_zombie on processing_progress (status, in_progress_since);
create index ix_processing_queue on processing_progress (stage, status)
    where status in ('pending', 'in_progress');


-- 租约式领取：远程 AI/IMAP 调用期间不持有数据库行锁。
-- 领取用比较并交换式的条件更新，受影响行数为零表示已被其他执行者取得。
create table processing_claim (
    message_id_pk bigint primary key,                     -- 逻辑引用 message
    claimed_by    text,                                   -- 执行者标识
    claim_until   timestamptz,                            -- 租约到期；崩溃后到期即可被重新领取
    version       int    not null default 0               -- 乐观锁
);


-- 用户预先声明的发件人规则，按已认证域名匹配。
--
-- 匹配的是 message.from_authenticated_domain 而非字面值：认证失败的邮件
-- 任何信任规则都不生效。域名模式按分段逐段比较（* 恰好一层，+ 任意层含裸域名），
-- 不用正则。
--
-- 规则变更不回溯已判定的邮件：判定在收信时一次完成并写入 message.category。
create table sender_rule (
    id             bigint      primary key generated by default as identity,
    rule_type      text        not null,
    domain_pattern text        not null,                  -- `*.a.com` 或 `+.a.com`
    enabled        boolean     not null default true,
    updated_at     timestamptz not null default now(),

    constraint ck_sender_rule_type check (rule_type in ('block', 'trust')),
    constraint uk_sender_rule unique (rule_type, domain_pattern)
);


