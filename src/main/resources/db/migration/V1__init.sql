-- 访问与应用配置（3 张）
-- ───────────────────────────────────────────────────────────────────────────

-- 登录凭据。单用户系统通常一行。
--
-- 不设 salt 与 algorithm 两列：现代密码哈希的输出字符串本身已内嵌盐与算法参数
-- （{bcrypt}$2a$10$<盐 22 字符><哈希>）。PasswordEncoder 的接口是 encode(明文) → 字符串、
-- matches(明文, 编码串) → boolean，从不单独传盐；另存一列 salt 没有任何代码会读，
-- 反而会诱导实现绕过标准编码器手工拼盐。
--
-- 登录失败限流在内存中做，不落库：重启清零可接受，不值得为它建表。
create table owner_credential (
    id            bigint      primary key generated by default as identity,
    username      text        not null,
    password_hash text        not null,                   -- PasswordEncoder 的完整编码字符串
    updated_at    timestamptz not null default now(),

    -- 防止误插两行导致登录取哪行不确定
    constraint uk_owner_credential_username unique (username)
);


-- 外部凭据，AES-GCM 可逆加密保存。密钥由环境变量注入，既不入仓也不入库——
-- 因此仅取得数据库副本无法解出外部凭据，需要服务器环境与数据库同时失守。
--
-- 密钥缺失但库中已存在密文时必须启动失败并明确报错，不允许静默生成新密钥
-- （那会让既有凭据永久无法解密）。
--
-- 不设 associated_data 列：AES-GCM 的 AAD 由代码按固定规则拼出
-- （secret_type + ':' + mail_account_id），一处定义。存一份的唯一后果是
-- 它与解密时重算的值若有任何差异，解密直接失败且极难排查。
create table external_account_secret (
    id              bigint      primary key generated by default as identity,
    mail_account_id bigint,                               -- 逻辑引用 mail_account；AI API key 不绑定账号时为 null
    secret_type     text        not null,
    ciphertext      bytea       not null,
    nonce           bytea       not null,                 -- GCMParameterSpec 需显式传入
    updated_at      timestamptz not null default now(),

    constraint ck_external_secret_type check (
        secret_type in ('imap_password', 'smtp_password', 'ai_api_key', 'exa_api_key', 'tavily_api_key'))
);

-- 【NULLS NOT DISTINCT 不能漏】AI API key 不绑定邮箱账号，mail_account_id 为 null。
-- PostgreSQL 默认语义下 NULL 彼此不相等，漏掉该子句能插入任意多条
-- (NULL, 'ai_api_key')，取用时无法确定该用哪条——而且不报错。
create unique index uk_external_account_secret
    on external_account_secret (mail_account_id, secret_type) nulls not distinct;


-- 单行表，装用户可在界面上调的参数。
--
-- 为什么一列一个参数而不是 setting_key/setting_value 两列：key-value 表里所有值
-- 都是 text，search_result_limit = -5 这种非法值数据库拦不住（它只看到两个字符），
-- 要等到真去检索时才炸；而 typed column + check 约束当场拒绝。
-- 代价是加参数要改表结构——但这套参数是封闭集合、变化极慢。
--
-- 不放进本表的配置：加密主密钥（环境变量）、数据库连接、AI API key（凭据，
-- 归 external_account_secret）。
create table app_setting (
    -- 单行守卫。没有它，一次 INSERT 失误就会出现两行配置，
    -- 而代码不会报错，只会随机读到一行
    id smallint primary key,

    -- ── 护栏参数 9 项 ───────────────────────────────────────
    initial_sync_days        int not null default 7,       -- 只影响此后新加入账号的首次同步
    thread_size_limit        int not null default 100,     -- 下一次归并生效，不回溯拆分已超限的会话
    processing_retry_limit   int not null default 3,
    search_result_limit      int not null default 20,
    turn_model_call_limit    int not null default 10,      -- Spring AI 工具循环无内置上限，全靠这个
    turn_timeout_seconds     int not null default 120,     -- 立即作用于正在跑的 Turn（不存 deadline_at）
    pending_action_ttl_hours int not null default 24,      -- 只影响新建的提案，已有行 expires_at 不重算
    tool_timeout_seconds     int not null default 20,
    smtp_timeout_seconds     int not null default 20,

    -- ── AI 连接 5 项（API key 是凭据，不在本表）────────────────
    ai_provider           text not null default 'openai',
    ai_base_url           text,                            -- null 表示用该 provider 的官方地址
    ai_model              text,                            -- null 表示未配置，AI 功能整体不可用（正常初始状态）
    -- 模型上下文窗口，单位 k（128 = 128000 token）。跟着型号走，换型号要改它。
    -- 系统不会根据型号名自动填：型号名是可以随便填的字符串（可能是自建服务或代理），
    -- 系统无从知道它对应多大窗口。下一轮提问时生效，不回溯重压已有对话
    ai_context_window_k   int  not null default 128,
    ai_timeout_seconds    int  not null default 60,

    -- ── AI 判定策略 ────────────────────────────────────────
    -- 垃圾判断只执行一次无工具 ChatModel 调用；category='spam' 是垃圾邮件唯一分类事实，
    -- 翻译目标固定为 zh-CN（语言判断与翻译由下方 ai_language_translation_enabled 一并控制）。
    spam_classification_threshold numeric(4, 3) not null default 0.800,
    spam_judgment_prompt          text         not null default $spam_policy$
请判断邮件内容成为垃圾邮件或恶意邮件的倾向，输出 0 到 1 的分数；分数越高，越应归入垃圾邮件。

评分时遵守以下边界：
- 不要仅因邮件所属领域、发件人显示名、群发形式或 DKIM 失败就判为垃圾。
- 验证码、账单、收据、发货、密码重置、政策通知、账户安全提醒和正常工作往来通常应为低分。
- 正常促销属于 promotion，不等于 spam；内容真实、来源清晰且没有欺骗性的商业推广通常不应得到垃圾高分。
- 免费或高性价比活动若时间、地点、参与门槛、福利内容和领取路径清晰，可作为有参与价值的信息保留，不要仅因宣传属性判为垃圾。
- 诈骗、钓鱼、冒充身份、诱导提交凭据或付款、恶意链接或附件诱导、虚假承诺、标题党、SEO 堆词、欺骗性营销、纯付费广告和几乎没有实质信息的空洞群发通常应为高分。
- 分数只表达垃圾倾向，不表达邮件重要性、文章质量或发件人可信度。
$spam_policy$,

    -- ── 六个 AI 阶段开关 ────────────────────────────────────
    -- 前五个是流水线阶段，关掉即在【阶段游标推进时】跳过；
    -- 第六个不是流水线阶段（会话摘要点开时现算），关掉即让那个接口返回 409。
    -- 开关不回溯：改开关不触发任何补跑，已打好的标签、已写好的摘要都留在库里
    ai_spam_check_enabled     boolean not null default true,
    ai_classify_enabled       boolean not null default true,
    ai_tagging_enabled        boolean not null default true,
    ai_summary_enabled        boolean not null default true,
    ai_language_translation_enabled boolean not null default true,
    ai_thread_summary_enabled boolean not null default true,

    -- ── 邮件生命周期自动化 ──────────────────────────────────
    auto_sync_enabled          boolean not null default true,
    imap_sync_interval_seconds int    not null default 60,
    auto_delete_enabled        boolean not null default true,
    message_retention_days     int    not null default 30,

    updated_at timestamptz not null default now(),

    constraint ck_app_setting_single_row check (id = 1),

    constraint ck_initial_sync_days        check (initial_sync_days between 1 and 365),
    constraint ck_thread_size_limit        check (thread_size_limit between 10 and 10000),
    constraint ck_processing_retry_limit   check (processing_retry_limit between 0 and 20),
    constraint ck_search_result_limit      check (search_result_limit between 1 and 200),
    constraint ck_turn_model_call_limit    check (turn_model_call_limit between 1 and 50),
    constraint ck_turn_timeout_seconds     check (turn_timeout_seconds between 10 and 1800),
    constraint ck_pending_action_ttl_hours check (pending_action_ttl_hours between 1 and 720),

    -- 【两个超时参数的下限锁 5 秒，界面必须给出警告】
    --
    -- smtp_timeout_seconds 调太小会让正常发信被判 indeterminate，而结果不确定的
    -- 邮件不入库——于是信实际发出去了、系统里没有记录、用户以为没发又发一遍。
    -- 这是用户能给自己造出的最坑的一种配置。
    --
    -- tool_timeout_seconds 调太小会让 IMAP 检索一类的慢工具永远超时，
    -- 表现为"AI 什么都查不到"而不是报错。
    constraint ck_tool_timeout_seconds check (tool_timeout_seconds between 5 and 300),
    constraint ck_smtp_timeout_seconds check (smtp_timeout_seconds between 5 and 300),

    constraint ck_ai_provider           check (ai_provider in ('openai', 'anthropic')),
    constraint ck_ai_context_window_k   check (ai_context_window_k between 4 and 2000),
    constraint ck_ai_timeout_seconds    check (ai_timeout_seconds between 5 and 600),

    -- AI 判定策略约束
    constraint ck_spam_classification_threshold
        check (spam_classification_threshold between 0 and 1),
    constraint ck_spam_judgment_prompt
        check (char_length(btrim(spam_judgment_prompt)) between 1 and 20000),

    -- 邮件生命周期自动化约束
    constraint ck_imap_sync_interval_seconds
        check (imap_sync_interval_seconds between 30 and 3600),
    constraint ck_message_retention_days
        check (message_retention_days between 1 and 3650)
);

